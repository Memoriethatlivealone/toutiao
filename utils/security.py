"""安全相关工具：密码加密与校验。

统一在这里维护密码算法，业务代码（如 crud/users.py）只调用
hash_password / verify_password，不直接依赖 passlib。
"""

from passlib.context import CryptContext

# ---------------------------------------------------------------------------
# 一、创建密码加密上下文
# ---------------------------------------------------------------------------
# CryptContext 统一管理「用哪种算法加密」和「怎么校验」两个问题
# schemes=["bcrypt"]：使用 bcrypt 算法，它会自动生成随机盐，
#   所以同一个密码每次加密出来的哈希都不一样，无法通过哈希反推出明文
# deprecated="auto"：校验时如果发现旧算法生成的哈希，会自动标记为过时，
#   以后换算法时老密码也能继续校验，用户下次登录再平滑升级
pwd_context = CryptContext(schemes=["bcrypt"], deprecated="auto")


# ---------------------------------------------------------------------------
# 二、加密：明文密码 -> 哈希
# ---------------------------------------------------------------------------
def hash_password(password: str) -> str:
    """把明文密码加密成哈希字符串，数据库里只存这个哈希，绝不能存明文。"""
    return pwd_context.hash(password)


# ---------------------------------------------------------------------------
# 三、密码校验：明文密码 + 数据库里的哈希 -> 是否匹配
# ---------------------------------------------------------------------------
def verify_password(plain_password: str, hashed_password: str) -> bool:
    """校验用户输入的明文密码与数据库中的哈希是否匹配，匹配返回 True。"""
    # verify 会从哈希里解析出盐和算法，用同样的方式重新计算再比对，
    # 而不是把明文重新加密后直接比较字符串（因为每次盐都不同）
    return pwd_context.verify(plain_password, hashed_password)